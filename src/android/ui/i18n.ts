const CATALOGS = {en, pt}

export type UiLang = keyof typeof CATALOGS

export function pickUiLang(language: string): UiLang {
	return language.toLowerCase().startsWith('pt') ? 'pt' : 'en'
}

let catalog: Record<MessageKey, string> = en

export function setUiLang(lang: UiLang): void {
	catalog = CATALOGS[lang]
}

export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
	return catalog[key].replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole))
}

